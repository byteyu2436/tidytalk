import AppKit
import Carbon.HIToolbox

/// 写入剪贴板 → 模拟 Cmd+V → 恢复原剪贴板中的内容（文字、图片、文件等）。
@MainActor
enum PasteService {
    /// 留给目标应用读取剪贴板的时间。
    static let restoreDelay: Duration = .milliseconds(600)
    /// 超过这个大小的剪贴板内容只恢复其中的文字，避免一次占用太多内存。
    static let snapshotLimit = 64 * 1024 * 1024

    /// 让剪贴板管理工具忽略这次临时写入（nspasteboard.org 约定）。
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    static func paste(_ text: String) async {
        let pasteboard = NSPasteboard.general
        let previous = snapshot(pasteboard)

        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: transientType)
        item.setData(Data(), forType: autoGeneratedType)
        pasteboard.writeObjects([item])
        let ourChange = pasteboard.changeCount

        postCommandV()

        try? await Task.sleep(for: restoreDelay)

        // 期间用户又复制了别的东西，就不覆盖
        guard pasteboard.changeCount == ourChange else { return }
        restore(previous, to: pasteboard)
    }

    /// 剪贴板里每一项的所有格式和数据。
    typealias Snapshot = [[(NSPasteboard.PasteboardType, Data)]]

    /// 读取剪贴板全部内容。内容过大时只保留文字。
    static func snapshot(_ pasteboard: NSPasteboard) -> Snapshot {
        var items: Snapshot = []
        var total = 0
        for item in pasteboard.pasteboardItems ?? [] {
            var entries: [(NSPasteboard.PasteboardType, Data)] = []
            for type in item.types {
                guard let data = item.data(forType: type) else { continue }
                total += data.count
                if total > snapshotLimit {
                    return pasteboard.string(forType: .string).map { [[(.string, Data($0.utf8))]] } ?? []
                }
                entries.append((type, data))
            }
            if !entries.isEmpty { items.append(entries) }
        }
        return items
    }

    static func restore(_ snapshot: Snapshot, to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        guard !snapshot.isEmpty else { return }
        let items = snapshot.map { entries in
            let item = NSPasteboardItem()
            for (type, data) in entries { item.setData(data, forType: type) }
            return item
        }
        pasteboard.writeObjects(items)
    }

    private static func postCommandV() {
        postCommandShortcut("v", fallback: CGKeyCode(kVK_ANSI_V))
    }

    /// 模拟 Cmd+某个字母，带上标记让自己的按键监听忽略它。
    static func postCommandShortcut(_ character: Unicode.Scalar, fallback: CGKeyCode) {
        let source = CGEventSource(stateID: .hidSystemState)
        let key = keyCode(for: character) ?? fallback
        for keyDown in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: keyDown) else { continue }
            event.flags = .maskCommand
            event.setIntegerValueField(.eventSourceUserData, value: HotkeyMonitor.syntheticEventMarker)
            event.post(tap: .cghidEventTap)
        }
    }

    /// 当前键盘布局下按住 Cmd 时输出该字母的键位（兼容 Dvorak 等布局），找不到时返回 nil。
    private static func keyCode(for character: Unicode.Scalar) -> CGKeyCode? {
        guard let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
              let raw = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData)
        else { return nil }

        let data = Unmanaged<CFData>.fromOpaque(raw).takeUnretainedValue() as Data
        return data.withUnsafeBytes { bytes -> CGKeyCode? in
            guard let layout = bytes.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self) else { return nil }
            let modifiers = UInt32((cmdKey >> 8) & 0xFF)
            for code in 0..<128 {
                var deadKeys: UInt32 = 0
                var length = 0
                var chars = [UniChar](repeating: 0, count: 4)
                let status = UCKeyTranslate(layout, UInt16(code), UInt16(kUCKeyActionDown), modifiers,
                                            UInt32(LMGetKbdType()), OptionBits(kUCKeyTranslateNoDeadKeysBit),
                                            &deadKeys, chars.count, &length, &chars)
                if status == noErr, length == 1, chars[0] == UniChar(character.value) {
                    return CGKeyCode(code)
                }
            }
            return nil
        }
    }
}
