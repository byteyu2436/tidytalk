import AppKit
import Carbon.HIToolbox
import TidytalkCore

/// 写入剪贴板 → 模拟 Cmd+V → 恢复原剪贴板中的内容（文字、图片、文件等）。
///
/// 剪贴板里放的是"用到时再提供"的文字：目标应用真正读取时才回调我们，读完再恢复（见 `PasteReceipts`），
/// 不用猜固定的等待时间，应用卡顿时也不会读到恢复后的旧内容。
@MainActor
enum PasteService {
    /// 超过这个大小的剪贴板内容只恢复其中的文字，避免一次占用太多内存。
    static let snapshotLimit = 64 * 1024 * 1024
    /// 检查是否可以恢复的间隔。
    private static let pollInterval: Duration = .milliseconds(15)

    /// 让剪贴板管理工具忽略这次临时写入（nspasteboard.org 约定）。
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    private static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")

    /// 上一次粘贴还没恢复剪贴板时又开始新的粘贴：先把上一次恢复掉，保证新的快照是用户自己的内容。
    private static var pending: (() -> Void)?

    /// 立即恢复还在等待的剪贴板（退出应用时调用）。
    static func finishPending() {
        pending?()
    }

    /// 等待恢复剪贴板的后台任务，开发测试时用 `waitUntilRestored()` 等它结束。
    private static var restoreTask: Task<Void, Never>?

    static func waitUntilRestored() async {
        await restoreTask?.value
    }

    /// 写入剪贴板并发出 ⌘V 后立即返回；读取回执和恢复剪贴板在后台进行，不耽误下一次说话。
    ///
    /// - Parameters:
    ///   - pasteboard: 默认是系统剪贴板；开发测试时传入独立的剪贴板。
    ///   - sendPaste: 默认模拟 ⌘V；开发测试时换成模拟的读取。
    static func paste(_ text: String, pasteboard: NSPasteboard = .general,
                      sendPaste: @MainActor () -> Void = postCommandV) async {
        pending?()
        let previous = snapshot(pasteboard)

        let provider = PromisedText(text)
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setDataProvider(provider, forTypes: [.string])
        item.setData(Data(), forType: transientType)
        item.setData(Data(), forType: autoGeneratedType)
        item.setData(Data(), forType: concealedType)
        pasteboard.writeObjects([item])
        let ourChange = pasteboard.changeCount

        let state = RestoreState()
        let finish = {
            guard !state.finished else { return }
            state.finished = true
            pending = nil
            // 期间用户又复制了别的东西，就不覆盖
            guard pasteboard.changeCount == ourChange else { return }
            restore(previous, to: pasteboard)
        }
        pending = finish

        provider.receipts.pasting(at: ProcessInfo.processInfo.systemUptime)
        sendPaste()

        restoreTask = Task { @MainActor in
            while !state.finished {
                try? await Task.sleep(for: pollInterval)
                // 只用 changeCount 判断是否被替换：文字提供完以后系统也会通知"不再需要提供者"
                if pasteboard.changeCount != ourChange { provider.receipts.contentReplaced() }
                switch provider.receipts.decision(at: ProcessInfo.processInfo.systemUptime) {
                case .wait: continue
                case .restore: finish()
                case .keep:
                    state.finished = true
                    pending = nil
                }
            }
        }
    }

    @MainActor
    private final class RestoreState {
        var finished = false
    }

    /// 剪贴板里每一项的所有格式和数据。
    typealias Snapshot = [[(NSPasteboard.PasteboardType, Data)]]

    /// 读取剪贴板全部内容。内容过大时只保留文字。
    static func snapshot(_ pasteboard: NSPasteboard) -> Snapshot {
        var items: Snapshot = []
        var total = 0
        for item in pasteboard.pasteboardItems ?? [] {
            var entries: [(NSPasteboard.PasteboardType, Data)] = []
            // 跳过系统按需转换出来的动态类型（dyn.*）：读取它们会让源应用当场生成数据，
            // 复制了大图时会卡一下；恢复时系统会从原始格式重新转换
            for type in item.types where !type.rawValue.hasPrefix("dyn.") {
                guard let data = item.data(forType: type) else { continue }
                total += data.count
                if total > snapshotLimit {
                    return pasteboard.string(forType: .string).map { [[(.string, Data($0.utf8))]] } ?? []
                }
                entries.append((type, data))
            }
            if !entries.isEmpty { items.append(entries) }
        }
        return items
    }

    static func restore(_ snapshot: Snapshot, to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        guard !snapshot.isEmpty else { return }
        let items = snapshot.map { entries in
            let item = NSPasteboardItem()
            for (type, data) in entries { item.setData(data, forType: type) }
            return item
        }
        pasteboard.writeObjects(items)
    }

    static func postCommandV() {
        postCommandShortcut("v", fallback: CGKeyCode(kVK_ANSI_V))
    }

    /// 模拟 Cmd+某个字母，带上标记让自己的按键监听忽略它。
    static func postCommandShortcut(_ character: Unicode.Scalar, fallback: CGKeyCode) {
        let source = CGEventSource(stateID: .hidSystemState)
        let key = keyCode(for: character) ?? fallback
        for keyDown in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: keyDown) else { continue }
            event.flags = .maskCommand
            event.setIntegerValueField(.eventSourceUserData, value: HotkeyMonitor.syntheticEventMarker)
            event.post(tap: .cghidEventTap)
        }
    }

    /// 当前键盘布局下按住 Cmd 时输出该字母的键位（兼容 Dvorak 等布局），找不到时返回 nil。
    private static func keyCode(for character: Unicode.Scalar) -> CGKeyCode? {
        guard let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
              let raw = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData)
        else { return nil }

        let data = Unmanaged<CFData>.fromOpaque(raw).takeUnretainedValue() as Data
        return data.withUnsafeBytes { bytes -> CGKeyCode? in
            guard let layout = bytes.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self) else { return nil }
            let modifiers = UInt32((cmdKey >> 8) & 0xFF)
            for code in 0..<128 {
                var deadKeys: UInt32 = 0
                var length = 0
                var chars = [UniChar](repeating: 0, count: 4)
                let status = UCKeyTranslate(layout, UInt16(code), UInt16(kUCKeyActionDown), modifiers,
                                            UInt32(LMGetKbdType()), OptionBits(kUCKeyTranslateNoDeadKeysBit),
                                            &deadKeys, chars.count, &length, &chars)
                if status == noErr, length == 1, chars[0] == UniChar(character.value) {
                    return CGKeyCode(code)
                }
            }
            return nil
        }
    }
}

/// 粘贴的文字：目标应用读取时才提供，每次读取都记一次回执。
@MainActor
private final class PromisedText: NSObject, NSPasteboardItemDataProvider {
    nonisolated let text: String
    var receipts = PasteReceipts()

    init(_ text: String) {
        self.text = text
    }

    nonisolated func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem,
                                provideDataForType type: NSPasteboard.PasteboardType) {
        item.setString(text, forType: type)
        let time = ProcessInfo.processInfo.systemUptime
        onMain { $0.receipts.read(at: time) }
    }

    /// 回调一般在主线程上；万一不是，转到主线程再记录。
    private nonisolated func onMain(_ body: @escaping @MainActor (PromisedText) -> Void) {
        if Thread.isMainThread {
            MainActor.assumeIsolated { body(self) }
        } else {
            DispatchQueue.main.async { body(self) }
        }
    }
}
